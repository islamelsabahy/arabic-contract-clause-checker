"""Generate the browser files that must stay in sync with the Python reference.

    python scripts/build_web_data.py          # (re)write the generated files
    python scripts/build_web_data.py --check  # exit 1 if any is stale (used by the tests)

* docs/rules.js      : clause/risk rules, normaliser tables and splitter, read from contractcheck/.
* docs/samples.js    : the three fictional sample contracts for the page's "load sample" buttons.
* tests/vectors.json : texts plus the report Python produces; docs/checker.js must reproduce it exactly.
"""
import json
import os
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, ROOT)

from contractcheck import checker  # noqa: E402
from contractcheck.checker import DISCLAIMER_AR, DISCLAIMER_EN, analyze, normalize, to_dict  # noqa: E402
from contractcheck.rules import CLAUSES, RISKS  # noqa: E402

SAMPLE_FILES = ("sale_good.txt", "sale_risky.txt", "lease_risky.txt")


def _read(name):
    with open(os.path.join(ROOT, "sample-data", name), encoding="utf-8") as fh:
        return fh.read()


def _js_wrap(global_name, payload, header):
    body = json.dumps(payload, ensure_ascii=False, indent=1)
    return (f"// GENERATED by scripts/build_web_data.py from {header}. Do not edit.\n"
            "(function (root, factory) {\n"
            "  if (typeof module === 'object' && module.exports) module.exports = factory();\n"
            f"  else root.{global_name} = factory();\n"
            "})(typeof self !== 'undefined' ? self : this, function () {\n"
            "  return " + body.replace("\n", "\n  ") + ";\n"
            "});\n")


def rules_js():
    trans = {chr(k): ("" if v is None else v) for k, v in checker._TRANS.items()}
    payload = {
        "tashkeel": checker._TASHKEEL.pattern,
        "invisible": checker._INVISIBLE.pattern,
        "whitespace": checker._WS.pattern,
        "split": checker._SPLIT.pattern,
        "translate": trans,
        "disclaimer": {"en": DISCLAIMER_EN, "ar": DISCLAIMER_AR},
        "clauses": [{"id": c.id, "en": c.en, "ar": c.ar, "patterns": list(c.patterns), "severity": c.severity,
                     "tip_en": c.tip_en, "tip_ar": c.tip_ar, "kinds": list(c.kinds)} for c in CLAUSES],
        "risks": [{"id": r.id, "en": r.en, "ar": r.ar, "pattern": r.pattern, "severity": r.severity,
                   "tip_en": r.tip_en, "tip_ar": r.tip_ar, "kinds": list(r.kinds), "scope": r.scope}
                  for r in RISKS],
    }
    return _js_wrap("CONTRACT_RULES", payload, "contractcheck/rules.py and checker.py")


def samples_js():
    payload = {name[:-4]: _read(name) for name in SAMPLE_FILES}
    body = json.dumps(payload, ensure_ascii=False, indent=1)
    return ("// GENERATED by scripts/build_web_data.py from sample-data/. Do not edit.\n"
            "window.CONTRACT_SAMPLES = " + body + ";\n")


