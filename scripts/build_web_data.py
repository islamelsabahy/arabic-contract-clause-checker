    def add(name, text):
        for kind in ("sale", "lease"):
            t.append((f"{name} [{kind}]", text, kind))

    for f in SAMPLE_FILES:
        add(f, _read(f))
    add("empty", "")
    add("whitespace only", "  \n\t \n")
    add("diacritics hide nothing", "لا يُرَدُّ أي مبلغ مسدد تحت أي ظرف. فَسْخ بدون إنذار.")
    add("penalty with percent", "غرامة التأخير 2% من قيمة القسط.")
    add("penalty without figure", "يلتزم المشتري بغرامة تأخير عند التأخر في السداد.")
    add("penalty figure in next sentence", "يلتزم المشتري بغرامة تأخير. وتحسب بواقع ٢ في المائة شهرياً.")
    add("penalty figures in other paragraph", "غرامة تأخير على المشتري.\n\nالسعر 100 ألف.")
    add("arabic indic digits", "الغرامة ٥٪ من الثمن، ومساحة الوحدة ١٢٠ م2")
    add("prefixed words", "يخضع هذا العقد للقانون المصري ومحاكم القاهرة وللتحكيم.")
    add("blanks", "الاسم .......... الرقم القومي ____ ……")
    add("ta marbuta and ya variants", "مساحه الوحده 90 متر مربع، والمبلغ غير قابله للاسترداد")
    add("rent increase without percent", "يحق للمؤجر رفع الأجرة كل سنة بالنسبة التي يراها.")
    add("rent increase with percent", "يحق للمؤجر زيادة الأجرة سنوياً بنسبة 10%.")
    add("sole discretion", "يتم التمديد وفق تقدير الشركة وحدها. ميعاد التسليم قابل للتمديد.")
    add("waiver", "يتنازل المشتري عن كافة حقوقه ويتم إبراء ذمة الشركة.")
    add("automatic termination", "يعتبر العقد مفسوخاً من تلقاء نفسه عند التأخر.")
    add("many excerpts", "\n".join(f"لا يرد المبلغ رقم {i}." for i in range(6)))
    add("long excerpt", "لا يرد " + "كلمة " * 120)
